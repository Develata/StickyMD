//! The macOS app fingerprint follows what can reach the app and nothing else: a release version,
//! documents, the Windows host and the tooling leave it unchanged; product sources, packaging,
//! manifests, the build identity and any unlisted file change it.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use super::fingerprint as mac_app_inputs;

const BUILD: &[u8] = b"rustc 1.97.1\nsdk 27.2\n";

fn root_manifest(version: &str) -> String {
    format!(
        "[workspace]\nresolver = \"2\"\nmembers = [\n    \"crates/stickymd-core\",\n    \"apps/stickymd-mac\",\n]\n\n[workspace.package]\nversion = \"{version}\"\nedition = \"2024\"\n"
    )
}

fn lockfile(version: &str) -> String {
    format!(
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"stickymd-core\"\nversion = \"{version}\"\n\n[[package]]\nname = \"stickymd-mac\"\nversion = \"{version}\"\ndependencies = [\n \"stickymd-core\",\n]\n"
    )
}

/// The fixture repository and the temporary directory that owns it (removed on drop).
struct Repository(
    PathBuf,
    #[allow(dead_code)] crate::temporary::TemporaryDirectory,
);

impl Repository {
    fn new() -> Self {
        let directory =
            crate::temporary::TemporaryDirectory::new("mac-fixture").expect("fixture directory");
        let root = directory.path().join("repository");
        fs::create_dir(&root).expect("exclusive fixture directory");
        let repository = Self(root, directory);
        repository.write("Cargo.toml", &root_manifest("0.1.3"));
        repository.write("Cargo.lock", &lockfile("0.1.3"));
        repository.write(
            "crates/stickymd-core/Cargo.toml",
            "[package]\nname = \"stickymd-core\"\nversion.workspace = true\nedition.workspace = true\npublish = false\n",
        );
        repository.write(
            "apps/stickymd-mac/Cargo.toml",
            "[package]\nname = \"stickymd-mac\"\nversion.workspace = true\nedition.workspace = true\npublish = false\n\n[dependencies]\nstickymd-core = { path = \"../../crates/stickymd-core\" }\n",
        );
        for path in [
            "crates/stickymd-core/src/lib.rs",
            "apps/stickymd-mac/src/main.rs",
            "apps/stickymd-mac/packaging/Info.plist",
            "apps/stickymd-win/src/main.rs",
            "tools/verification-tool/src/main.rs",
            "docs/plan/02_positioning_and_scope.md",
            "tests/fixtures/performance/typical-note-seed.md",
            "README.md",
            "CHANGELOG.md",
            "deny.toml",
        ] {
            repository.write(path, "initial");
        }
        assert!(
            Command::new("git")
                .args(["init", "--quiet"])
                .current_dir(&repository.0)
                .status()
                .expect("git init")
                .success()
        );
        repository
    }

    fn write(&self, relative: &str, text: &str) {
        let path = self.0.join(relative);
        fs::create_dir_all(path.parent().expect("parent")).expect("mkdir");
        fs::write(path, text).expect("write fixture");
    }

    fn inputs(&self) -> String {
        mac_app_inputs(&self.0, BUILD).expect("fingerprint")
    }

    fn path(&self) -> &Path {
        &self.0
    }
}

#[test]
fn a_release_version_documents_the_windows_host_and_tooling_leave_it_unchanged() {
    let repository = Repository::new();
    let before = repository.inputs();
    assert_eq!(before.len(), 64);
    repository.write("Cargo.toml", &root_manifest("0.2.0"));
    repository.write("Cargo.lock", &lockfile("0.2.0"));
    assert_eq!(repository.inputs(), before, "a release version alone");
    for path in [
        "apps/stickymd-win/src/main.rs",
        "tools/verification-tool/src/main.rs",
        "docs/plan/02_positioning_and_scope.md",
        "tests/fixtures/performance/typical-note-seed.md",
        "README.md",
        "CHANGELOG.md",
        "deny.toml",
    ] {
        repository.write(path, "changed");
        assert_eq!(repository.inputs(), before, "{path}");
    }
}

#[test]
fn product_sources_packaging_manifests_the_build_and_unlisted_files_change_it() {
    let repository = Repository::new();
    let mut previous = repository.inputs();
    let mut assert_changed = |what: &str, repository: &Repository| {
        let now = repository.inputs();
        assert_ne!(now, previous, "{what}");
        previous = now;
    };
    repository.write("crates/stickymd-core/src/lib.rs", "changed");
    assert_changed("a shared crate", &repository);
    repository.write("apps/stickymd-mac/src/main.rs", "changed");
    assert_changed("the macOS host", &repository);
    repository.write("apps/stickymd-mac/packaging/Info.plist", "changed");
    assert_changed("the packaging", &repository);
    repository.write(
        "apps/stickymd-mac/Cargo.toml",
        "[package]\nname = \"stickymd-mac\"\nversion.workspace = true\nedition.workspace = true\npublish = false\n\n[dependencies]\nstickymd-core = { path = \"../../crates/stickymd-core\", features = [] }\n",
    );
    assert_changed("a member manifest", &repository);
    repository.write(
        "Cargo.lock",
        &lockfile("0.1.3").replace("version = 4", "version = 3"),
    );
    assert_changed("the lockfile beyond its version labels", &repository);
    repository.write(".cargo/config.toml", "[build]\n");
    assert_changed("an unlisted file", &repository);
    assert_ne!(
        mac_app_inputs(repository.path(), b"rustc 1.98.0\nsdk 27.2\n").unwrap(),
        previous,
        "the build identity"
    );
}
